// =====================================================================
// GdiReceiptPrinter.cs — GrandCinemasPrintBridge
//
// WIDTH-SAFE REWRITE — fixes the overflow introduced when font sizes,
// bold weight, logo size and QR were increased to the approved 1.25x
// premium design.
//
// ROOT CAUSE (confirmed from the previous version of this file):
//   The old code used TWO different margin concepts —
//     usableWidth      = ReceiptLayoutConfig.UsableWidthPx   (one margin)
//     contentLeftPx     = OuterMarginPx + SideMarginPx        (two margins)
//   As long as fonts/logo were small, nothing actually reached the
//   disagreement zone, so it looked fine. Once font size, bold, logo
//   size and QR were all increased, elements started reaching the edge
//   defined by "usableWidth" — which was NOT the same edge the border/
//   physical paper actually used — so text and the logo rendered past
//   the real printable boundary and the POS80 head/driver silently
//   dropped whatever fell outside it (values disappearing entirely,
//   words cut mid-character, logo/border touching the edge).
//
// FIX — implemented in this file:
//   1. ONE safe content rectangle (ReceiptLayoutConfig.ContentLeft /
//      ContentRight / ContentWidth = 552px) used by EVERY renderer.
//   2. Real word-wrapping (WrapText) for Text elements and the movie
//      title / failure message / cinema name — long content grows
//      DOWN, never sideways.
//   3. Row values: measured at the approved font size first; if a
//      single unbreakable value (e.g. a long Booking ID) doesn't fit
//      the 58% column, auto-shrink that ONE value down to
//      MinFitFontSize before falling back to wrapping — never clipped.
//   4. Logo hard-capped to LogoMaxWidthPx (< ContentWidth), centered
//      inside the content rectangle, never the raw paper width.
//   5. QR capped to QrDisplaySizePx (well inside ContentWidth),
//      centered, generated dynamically per ticket via QRCoder — never
//      a static bridge asset (only the brand logo is static).
//   6. MeasureHeight() and DrawElements() remain the same single
//      code path (this was already correct) — so the calculated paper
//      height always matches what actually gets drawn; the cutter
//      never lands early.
// =====================================================================

