    // ── Wire model ────────────────────────────────────────────────────
    public enum ElementType { Text, Row, Image, Divider, Spacer, QrCode }
    public enum TextAlign { Left, Center, Right }

    public class ReceiptElement
    {
        public ElementType Type { get; set; }

        // Text
        public string Text { get; set; }
        public float FontSize { get; set; } = ReceiptLayoutConfig.NormalFontSize;
        public bool Bold { get; set; } = false;
        public TextAlign Align { get; set; } = TextAlign.Left;
        public string Color { get; set; } = "#000000"; // preview-only; physical print is always black

        // Image (receipt-specific images only — NOT the brand logo)
        public string ImageBase64 { get; set; }
        public int ImageHeightPx { get; set; } = 80;

        // Row
        public string LeftText { get; set; }
        public string RightText { get; set; }
        public float LeftFontSize { get; set; } = ReceiptLayoutConfig.LabelFontSize;
        public float RightFontSize { get; set; } = ReceiptLayoutConfig.NormalFontSize;
        public bool RightBold { get; set; } = true;

        // Spacer
        public int HeightPx { get; set; } = ReceiptLayoutConfig.SectionSpacingPx;

        // QrCode — dynamic, generated by the bridge from QrText.
        // QrText is whatever payload the frontend decided on (e.g.
        // "Booking ID: WLLLQRS\nSeat: R11S17"). The bridge never stores
        // or reuses a QR image — every ticket generates its own.
        public string QrText { get; set; }
        public string QrLabel { get; set; } = "Scan for Ticket Details";
    }

    public class ReceiptPrintRequest
    {
        public string ReceiptType { get; set; }
        public string BookingId { get; set; }
        public string WorkstationId { get; set; }
        public string CinemaId { get; set; }
        public List<ReceiptElement> Elements { get; set; } = new List<ReceiptElement>();
    }

    // ── The printer ─────────────────────────────────────────────────
    public static class GdiReceiptPrinter
    {
        private const string TargetPrinterName = "POS80";

        // ── Bridge-owned logo — loaded once, processed once ──────────
        private static Bitmap _processedLogo;
        private static bool _logoLoadAttempted;

        private static Bitmap GetProcessedLogo()
        {
            if (_logoLoadAttempted) return _processedLogo;
            _logoLoadAttempted = true;

            try
            {
                string assetPath = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Assets", "grand-cinemas-logo.png");
                if (!File.Exists(assetPath))
                {
                    Program.Log("Logo asset not found at: " + assetPath + " — receipts will print without a logo.");
                    return null;
                }

                using (var raw = new Bitmap(assetPath))
                {
                    // Preserve original tones (no forced black/white threshold —
                    // removed per earlier feedback that it over-darkened the logo).
                    _processedLogo = new Bitmap(raw);
                }
                Program.Log("Logo loaded from: " + assetPath);
            }
            catch (Exception ex)
            {
                Program.Log("Failed to load logo: " + ex.Message);
                _processedLogo = null;
            }

            return _processedLogo;
        }

        public static (bool Success, string Reason, string FilePath) Preview(ReceiptPrintRequest request)
        {
            Program.Log("Received /preview request. ReceiptType: " + (request?.ReceiptType ?? "(unspecified)") +
                " | Elements: " + (request?.Elements?.Count ?? 0));
            try
            {
                var fullElements = BuildFullElementList(request.Elements);
                int contentHeightPx = MeasureHeight(fullElements);
                Program.Log("Preview measured height: " + contentHeightPx + "px");

                if (contentHeightPx <= 0) return (false, "empty_elements", null);

                // Canvas is contentHeightPx + BorderBottomFeedPx tall — the
                // border itself is still drawn at contentHeightPx (unchanged
                // position), this just adds visible blank margin below it in
                // the preview so what you see here matches the extra cutter
                // clearance Print() now also reserves.
                int canvasHeightPx = contentHeightPx + ReceiptLayoutConfig.BorderBottomFeedPx;
                using (var bmp = new Bitmap(ReceiptLayoutConfig.PrintableWidthPx, canvasHeightPx))
                using (var g = Graphics.FromImage(bmp))
                {
                    g.Clear(Color.White);
                    g.PageUnit = GraphicsUnit.Pixel;
                    DrawElements(g, fullElements);
                    DrawOuterBorder(g, contentHeightPx);

                    string filePath = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "preview.png");
                    bmp.Save(filePath, ImageFormat.Png);
                    Program.Log("Preview saved to: " + filePath);
                    return (true, null, filePath);
                }
            }
            catch (Exception ex)
            {
                Program.Log("EXCEPTION in Preview(): " + ex);
                return (false, "draw_error: " + ex.Message, null);
            }
        }

        // Border sits exactly on the safe content rectangle — the SAME
        // ContentLeft/ContentRight every other element uses. Previously
        // this used a separate OuterMarginPx, which is how it could end
        // up NOT matching where text/logo actually stopped.
        private static void DrawOuterBorder(Graphics g, int contentHeightPx)
        {
            int left = ReceiptLayoutConfig.ContentLeft;
            int right = ReceiptLayoutConfig.ContentRight;
            using (var pen = new Pen(Color.Black, 1))
            {
                g.DrawRectangle(pen, left, ReceiptLayoutConfig.TopPaddingPx / 2,
                    right - left - 1,
                    contentHeightPx - ReceiptLayoutConfig.TopPaddingPx - 1);
            }
        }

        // ── PRODUCTION CALIBRATION — temporary, diagnostic only ──────────
        // Prints an mm ruler (0/10/20/.../70mm) plus the CURRENT
        // ContentLeft/ContentRight boundary as GDI actually draws it, and
        // logs every printer-reported dimension the calibration spec
        // asks for. This tells us, from REAL printed output + a ruler,
        // whether ReceiptLayoutConfig's 576px/552px assumption matches
        // what the POS80 driver is actually giving GDI at print time.
        //
        // Call via POST http://localhost:9131/calibrate
        // Remove the /calibrate route (or just stop calling it) once
        // calibration is done — this must never ship as a customer-
        // facing receipt.
        public static (bool Success, string Reason) PrintCalibration()
        {
            Program.Log("========== CALIBRATION PRINT START ==========");
            try
            {
                using (var doc = new PrintDocument())
                {
                    doc.PrinterSettings.PrinterName = TargetPrinterName;
                    if (!doc.PrinterSettings.IsValid)
                    {
                        Program.Log("CALIBRATION: printer not found: '" + TargetPrinterName + "'");
                        return (false, "printer_not_found");
                    }

                    // ── STAGE 1: driver defaults, BEFORE we touch anything ──
                    var ps = doc.PrinterSettings;
                    var defPage = ps.DefaultPageSettings;
                    Program.Log("CALIBRATION [BEFORE custom paper size]:");
                    Program.Log("  PrinterSettings.PrinterName = " + ps.PrinterName);
                    Program.Log("  PrinterSettings.IsValid = " + ps.IsValid);
                    Program.Log("  DefaultPageSettings.PaperSize = " + defPage.PaperSize.Width + " x " + defPage.PaperSize.Height + " (hundredths-inch), Kind=" + defPage.PaperSize.Kind);
                    Program.Log("  DefaultPageSettings.PrintableArea = " + defPage.PrintableArea);
                    Program.Log("  DefaultPageSettings.HardMarginX = " + defPage.HardMarginX + ", HardMarginY = " + defPage.HardMarginY);

                    doc.PrintController = new StandardPrintController();

                    // Requested custom page width — explicitly labeled as a
                    // REQUEST, not the production source of truth. Whatever
                    // the driver/GDI actually give back (logged below, and
                    // in e.Graphics.* inside PrintPage) is what matters.
                    int requestedWidthHundredths = (int)((ReceiptLayoutConfig.PrintableWidthPx / ReceiptLayoutConfig.Dpi) * 100);
                    int requestedHeightHundredths = (int)((1000 / ReceiptLayoutConfig.Dpi) * 100) + 20; // fixed test height
                    var customSize = new PaperSize("CalibrationTest", requestedWidthHundredths, requestedHeightHundredths);
                    doc.DefaultPageSettings.PaperSize = customSize;
                    doc.DefaultPageSettings.Margins = new Margins(0, 0, 0, 0);

                    double requestedWidthMm = requestedWidthHundredths / 100.0 * 25.4;
                    Program.Log("CALIBRATION [REQUESTED, not authoritative]: " + requestedWidthHundredths + " hundredths-inch => " +
                        ReceiptLayoutConfig.PrintableWidthPx + "px @ assumed " + ReceiptLayoutConfig.Dpi + " DPI => ~" + requestedWidthMm.ToString("F1") + "mm");

                    // ── STAGE 2: driver values AFTER we set the custom size ──
                    var afterPage = doc.DefaultPageSettings;
                    Program.Log("CALIBRATION [AFTER doc.DefaultPageSettings.PaperSize = customSize]:");
                    Program.Log("  DefaultPageSettings.PaperSize = " + afterPage.PaperSize.Width + " x " + afterPage.PaperSize.Height + " (hundredths-inch)");
                    Program.Log("  DefaultPageSettings.PrintableArea = " + afterPage.PrintableArea);
                    Program.Log("  DefaultPageSettings.HardMarginX = " + afterPage.HardMarginX + ", HardMarginY = " + afterPage.HardMarginY);

                    doc.PrintPage += (s, e) =>
                    {
                        // ── STAGE 3: the numbers that actually matter — from
                        // the REAL PrintPage event, not assumed constants. ──
                        Program.Log("CALIBRATION [DURING PrintPage — the numbers GDI is actually using]:");
                        Program.Log("  e.PageBounds = " + e.PageBounds);
                        Program.Log("  e.MarginBounds = " + e.MarginBounds);
                        Program.Log("  e.Graphics.VisibleClipBounds = " + e.Graphics.VisibleClipBounds);
                        Program.Log("  e.Graphics.DpiX = " + e.Graphics.DpiX + ", DpiY = " + e.Graphics.DpiY);
                        Program.Log("  e.Graphics.PageUnit (BEFORE fix) = " + e.Graphics.PageUnit);

                        var g = e.Graphics;
                        g.PageUnit = GraphicsUnit.Pixel; // same fix as Print() — see comment there
                        g.SmoothingMode = System.Drawing.Drawing2D.SmoothingMode.None; // crisp lines for measuring

                        Program.Log("  e.Graphics.PageUnit (AFTER fix) = " + g.PageUnit);
                        Program.Log("CALIBRATION SUMMARY: PAPER WIDTH=" + ReceiptLayoutConfig.PrintableWidthPx + "px" +
                            " | PRINTABLE WIDTH(driver clip)=" + e.Graphics.VisibleClipBounds.Width +
                            " | CONTENT LEFT=" + ReceiptLayoutConfig.ContentLeft +
                            " | CONTENT RIGHT=" + ReceiptLayoutConfig.ContentRight +
                            " | CONTENT WIDTH=" + ReceiptLayoutConfig.ContentWidth +
                            " | DPI=" + ReceiptLayoutConfig.Dpi +
                            " | PageUnit=" + g.PageUnit);

                        // mm -> px using the ACTUAL reported DpiX — never the
                        // assumed ReceiptLayoutConfig.Dpi. This is the whole
                        // point of the calibration print.
                        float pxPerMm = (float)(e.Graphics.DpiX / 25.4);
                        Program.Log("  computed pxPerMm (from real DpiX) = " + pxPerMm);

                        // Derive the three distinct boundaries this print is
                        // meant to separate. "Printable" comes from the
                        // driver's own PrintableArea (Stage 2) mapped into
                        // this page's pixel space via VisibleClipBounds —
                        // "Content" is today's ReceiptLayoutConfig guess.
                        float paperLeftPx = 0f;
                        float paperRightPx = ReceiptLayoutConfig.PrintableWidthPx;
                        float printableLeftPx = e.Graphics.VisibleClipBounds.Left;
                        float printableRightPx = e.Graphics.VisibleClipBounds.Right;
                        float contentLeftPx = ReceiptLayoutConfig.ContentLeft;
                        float contentRightPx = ReceiptLayoutConfig.ContentRight;
                        float centerXPx = ReceiptLayoutConfig.PrintableWidthPx / 2f;

                        using (var thinPen = new Pen(Color.Black, 1))       // PAPER boundary
                        using (var mediumPen = new Pen(Color.Black, 2))     // PRINTABLE boundary
                        using (var thickPen = new Pen(Color.Black, 4))      // CONTENT boundary (today's guess)
                        using (var labelFont = new Font("Arial", 13, FontStyle.Regular, GraphicsUnit.Pixel))
                        using (var smallFont = new Font("Arial", 11, FontStyle.Regular, GraphicsUnit.Pixel))
                        {
                            const int linesTop = 0, linesBottom = 260;

                            // PAPER LEFT / RIGHT — thin
                            g.DrawLine(thinPen, paperLeftPx, linesTop, paperLeftPx, linesBottom);
                            g.DrawLine(thinPen, paperRightPx - 1, linesTop, paperRightPx - 1, linesBottom);
                            g.DrawString("PAPER LEFT", smallFont, Brushes.Black, paperLeftPx + 2, linesTop + 2);
                            g.DrawString("PAPER RIGHT", smallFont, Brushes.Black, paperRightPx - 100, linesTop + 2);

                            // PRINTABLE LEFT / RIGHT — medium (from driver's real clip bounds)
                            g.DrawLine(mediumPen, printableLeftPx, linesTop, printableLeftPx, linesBottom);
                            g.DrawLine(mediumPen, printableRightPx, linesTop, printableRightPx, linesBottom);
                            g.DrawString("PRINTABLE LEFT", smallFont, Brushes.Black, printableLeftPx + 2, linesTop + 20);
                            g.DrawString("PRINTABLE RIGHT", smallFont, Brushes.Black, printableRightPx - 115, linesTop + 20);

                            // CONTENT LEFT / RIGHT — thick (today's ReceiptLayoutConfig guess)
                            g.DrawLine(thickPen, contentLeftPx, linesTop, contentLeftPx, linesBottom);
                            g.DrawLine(thickPen, contentRightPx, linesTop, contentRightPx, linesBottom);
                            g.DrawString("CONTENT LEFT", smallFont, Brushes.Black, contentLeftPx + 2, linesTop + 38);
                            g.DrawString("CONTENT RIGHT", smallFont, Brushes.Black, contentRightPx - 105, linesTop + 38);

                            // CENTER — thin, dashed-look via short segments
                            g.DrawLine(thinPen, centerXPx, linesTop, centerXPx, linesBottom);
                            g.DrawString("CENTER", smallFont, Brushes.Black, centerXPx - 25, linesTop + 56);

                            // mm ruler ticks: 0..70mm from the LEFT PAPER EDGE.
                            float rulerY = 280;
                            for (int mm = 0; mm <= 70; mm += 10)
                            {
                                float x = mm * pxPerMm;
                                g.DrawLine(thinPen, x, rulerY, x, rulerY + 50);
                                g.DrawString(mm + "mm", labelFont, Brushes.Black, x - 14, rulerY + 52);
                            }

                            // ── Self-documenting numbers printed on the ticket ──
                            float ty = rulerY + 90;
                            void Line(string text2) { g.DrawString(text2, smallFont, Brushes.Black, 4, ty); ty += 18; }

                            Line("Printer: " + TargetPrinterName);
                            Line("Graphics DPI: " + e.Graphics.DpiX + " x " + e.Graphics.DpiY);
                            Line("Page Bounds: " + e.PageBounds.Width + " x " + e.PageBounds.Height + "px");
                            Line("Margin Bounds: " + e.MarginBounds.Width + " x " + e.MarginBounds.Height + "px");
                            Line("Visible Clip: " + e.Graphics.VisibleClipBounds.Width.ToString("F0") + " x " + e.Graphics.VisibleClipBounds.Height.ToString("F0") + "px");
                            Line("Driver PrintableArea (after custom size): " + afterPage.PrintableArea.Width.ToString("F0") + " x " + afterPage.PrintableArea.Height.ToString("F0"));
                            Line("Hard Margin X: " + afterPage.HardMarginX.ToString("F1") + "  Hard Margin Y: " + afterPage.HardMarginY.ToString("F1"));
                            Line("Requested Width: " + ReceiptLayoutConfig.PrintableWidthPx + "px / ~" + requestedWidthMm.ToString("F1") + "mm (theoretical, NOT authoritative)");
                            Line("Current ContentLeft/Right: " + ReceiptLayoutConfig.ContentLeft + " / " + ReceiptLayoutConfig.ContentRight + "px");
                            Line("");
                            Line("Measure mm marks with a ruler.");
                            Line("Note the mm value where printing actually stops on the right.");
                        }

                        e.HasMorePages = false;
                    };

                    doc.Print();
                    Program.Log("========== CALIBRATION PRINT DONE — see CALIBRATION lines above ==========");
                    return (true, null);
                }
            }
            catch (Exception ex)
            {
                Program.Log("EXCEPTION in PrintCalibration(): " + ex);
                return (false, "draw_error: " + ex.Message);
            }
        }

        public static (bool Success, string Reason) Print(ReceiptPrintRequest request)
        {
            Program.Log("Received /print request. ReceiptType: " + (request?.ReceiptType ?? "(unspecified)") +
                " | Elements: " + (request?.Elements?.Count ?? 0));
            try
            {
                using (var doc = new PrintDocument())
                {
                    doc.PrinterSettings.PrinterName = TargetPrinterName;
                    if (!doc.PrinterSettings.IsValid)
                    {
                        Program.Log("Printer not found: '" + TargetPrinterName + "'");
                        return (false, "printer_not_found");
                    }
                    Program.Log("Printer: " + TargetPrinterName + " | Content width: " + ReceiptLayoutConfig.ContentWidth + "px (paper " + ReceiptLayoutConfig.PrintableWidthPx + "px)");

                    doc.PrintController = new StandardPrintController();

                    var fullElements = BuildFullElementList(request.Elements);
                    int contentHeightPx = MeasureHeight(fullElements);
                    Program.Log("Measured content height: " + contentHeightPx + "px");

                    if (contentHeightPx <= 0) return (false, "empty_elements");

                    // The border is still drawn at contentHeightPx (its
                    // position is unchanged) — BorderBottomFeedPx only adds
                    // blank paper AFTER it, so the POS80's auto-cut has
                    // definite clearance to fully feed the bottom border
                    // line past the print head before cutting. The old flat
                    // "+20" hundredths-inch fudge is folded into this named,
                    // documented constant instead of a magic number.
                    int widthHundredths = (int)((ReceiptLayoutConfig.PrintableWidthPx / ReceiptLayoutConfig.Dpi) * 100);
                    int heightHundredths = (int)(((contentHeightPx + ReceiptLayoutConfig.BorderBottomFeedPx) / ReceiptLayoutConfig.Dpi) * 100) + 20;

                    var customSize = new PaperSize("ReceiptCustom", widthHundredths, heightHundredths);
                    doc.DefaultPageSettings.PaperSize = customSize;
                    doc.DefaultPageSettings.Margins = new Margins(0, 0, 0, 0);
                    Program.Log("Paper size set: " + widthHundredths + "x" + heightHundredths + " (hundredths-inch)");

                    bool printed = false;
                    Exception drawError = null;

                    doc.PrintPage += (s, e) =>
                    {
                        Program.Log("PrintPage fired.");
                        Program.Log("PRINT CALIBRATION [BEFORE PageUnit fix]: e.Graphics.PageUnit = " + e.Graphics.PageUnit +
                            ", DpiX=" + e.Graphics.DpiX + ", DpiY=" + e.Graphics.DpiY +
                            ", e.PageBounds=" + e.PageBounds + ", e.MarginBounds=" + e.MarginBounds +
                            ", VisibleClipBounds=" + e.Graphics.VisibleClipBounds);

                        // ── THE FIX ─────────────────────────────────────────
                        // Without this line, e.Graphics defaults to
                        // GraphicsUnit.Display during the REAL PrintPage
                        // event, while MeasureHeight()/Preview() both draw
                        // in GraphicsUnit.Pixel. Those are two DIFFERENT
                        // coordinate systems, so the same numeric x/y/width
                        // values meant two different physical sizes
                        // depending on which pass drew them — which is
                        // exactly why /preview looked correct but the
                        // physical POS80 output came out oversized/clipped.
                        // This MUST run before any measurement or drawing
                        // touches e.Graphics, so both passes agree on what
                        // one unit means.
                        e.Graphics.PageUnit = GraphicsUnit.Pixel;

                        Program.Log("PRINT CALIBRATION [AFTER PageUnit fix]: e.Graphics.PageUnit = " + e.Graphics.PageUnit +
                            ", PrintableWidthPx=" + ReceiptLayoutConfig.PrintableWidthPx +
                            ", ContentLeft=" + ReceiptLayoutConfig.ContentLeft +
                            ", ContentRight=" + ReceiptLayoutConfig.ContentRight +
                            ", ContentWidth=" + ReceiptLayoutConfig.ContentWidth +
                            ", Dpi=" + ReceiptLayoutConfig.Dpi +
                            ", ReceiptHeightPx=" + contentHeightPx);

                        try
                        {
                            DrawElements(e.Graphics, fullElements);
                            DrawOuterBorder(e.Graphics, contentHeightPx);
                            printed = true;
                            Program.Log("Drawing completed.");
                        }
                        catch (Exception ex) { drawError = ex; }
                        e.HasMorePages = false;
                    };

                    doc.Print();

                    if (drawError != null)
                    {
                        Program.Log("Draw error: " + drawError.Message);
                        return (false, "draw_error");
                    }
                    if (!printed) return (false, "print_page_not_fired");

                    Program.Log("Print completed successfully.");
                    return (true, null);
                }
            }
            catch (Exception ex)
            {
                Program.Log("EXCEPTION in Print(): " + ex);
                return (false, "draw_error: " + ex.Message);
            }
        }

        private static List<ReceiptElement> BuildFullElementList(List<ReceiptElement> receiptSpecific)
        {
            var full = new List<ReceiptElement>();
            if (GetProcessedLogo() != null)
            {
                full.Add(new ReceiptElement { Type = ElementType.Image, ImageHeightPx = -1 });
                full.Add(new ReceiptElement { Type = ElementType.Spacer, HeightPx = ReceiptLayoutConfig.LogoBottomSpacingPx });
                full.Add(new ReceiptElement { Type = ElementType.Divider });
            }
            full.AddRange(receiptSpecific ?? new List<ReceiptElement>());
            return full;
        }

        private static int MeasureHeight(List<ReceiptElement> elements)
        {
            using (var scratch = new Bitmap(ReceiptLayoutConfig.PrintableWidthPx, 20000))
            using (var g = Graphics.FromImage(scratch))
            {
                g.PageUnit = GraphicsUnit.Pixel;
                return DrawElements(g, elements);
            }
        }

        // ── Word-wrap helper ────────────────────────────────────────
        // Splits text into lines that each fit within maxWidthPx at the
        // given font, breaking on spaces. A single word longer than
        // maxWidthPx is kept whole on its own line (never mid-character
        // truncated) — callers that can't tolerate that (Row values)
        // use FitFontToWidth instead/first.
        private static List<string> WrapText(Graphics g, string text, Font font, float maxWidthPx)
        {
            var lines = new List<string>();
            if (string.IsNullOrEmpty(text)) { lines.Add(""); return lines; }

            var words = text.Split(' ');
            string current = "";

            foreach (var word in words)
            {
                string candidate = current.Length == 0 ? word : current + " " + word;
                float w = g.MeasureString(candidate, font, int.MaxValue, StringFormat.GenericTypographic).Width;
                if (w <= maxWidthPx || current.Length == 0)
                {
                    current = candidate;
                }
                else
                {
                    lines.Add(current);
                    current = word;
                }
            }
            if (current.Length > 0) lines.Add(current);
            if (lines.Count == 0) lines.Add("");
            return lines;
        }

        // Shrinks font size (down to MinFitFontSize) until `text` fits
        // on ONE line within maxWidthPx. Used for Row values where
        // wrapping would make an identifier (Booking ID, seat code)
        // confusing to read — shrink first, only wrap as a last resort.
        // NOTE: this alone is NOT the hard guarantee — see WrapTextHard
        // below, which is what actually enforces "never crosses
        // ContentRight" for whatever font this returns.
        private static Font FitFontToWidth(Graphics g, string text, string fontFamily,
            float startSize, FontStyle style, float maxWidthPx)
        {
            float size = startSize;
            while (size > ReceiptLayoutConfig.MinFitFontSize)
            {
                var candidate = new Font(fontFamily, size, style, GraphicsUnit.Pixel);
                float w = g.MeasureString(text ?? "", candidate, int.MaxValue, StringFormat.GenericTypographic).Width;
                if (w <= maxWidthPx) return candidate;
                candidate.Dispose();
                size -= 0.5f;
            }
            return new Font(fontFamily, ReceiptLayoutConfig.MinFitFontSize, style, GraphicsUnit.Pixel);
        }

        // ── HARD containment guarantee ──────────────────────────────
        // WrapText() alone still leaves a gap: a single unbreakable word
        // (no spaces — a long Booking ID, a URL, a run-together string)
        // is kept whole even if it's wider than maxWidthPx. This method
        // closes that gap: it word-wraps first (preferred, keeps
        // identifiers readable), then for any resulting line that STILL
        // doesn't fit, it breaks that one line character-by-character
        // until every returned line is guaranteed <= maxWidthPx.
        //
        // This is what actually enforces the hard rule "no element may
        // ever draw outside ContentLeft..ContentRight" — FitFontToWidth
        // narrows the odds of needing this at all, but this is the
        // backstop that makes it unconditional regardless of font size
        // or how pathological the input string is.
        private static List<string> WrapTextHard(Graphics g, string text, Font font, float maxWidthPx)
        {
            var wordLines = WrapText(g, text, font, maxWidthPx);
            var result = new List<string>();

            foreach (var line in wordLines)
            {
                float w = g.MeasureString(line, font, int.MaxValue, StringFormat.GenericTypographic).Width;
                if (w <= maxWidthPx || line.Length == 0)
                {
                    result.Add(line);
                    continue;
                }

                // This line is one unbreakable word wider than the column
                // even at MinFitFontSize (FitFontToWidth already tried its
                // best) — break it character by character as the last
                // resort so it physically cannot cross ContentRight.
                string current = "";
                foreach (char c in line)
                {
                    string candidate = current + c;
                    float cw = g.MeasureString(candidate, font, int.MaxValue, StringFormat.GenericTypographic).Width;
                    if (cw <= maxWidthPx || current.Length == 0)
                    {
                        current = candidate;
                    }
                    else
                    {
                        result.Add(current);
                        current = c.ToString();
                    }
                }
                if (current.Length > 0) result.Add(current);
            }

            if (result.Count == 0) result.Add("");
            return result;
        }

        private static int DrawElements(Graphics g, List<ReceiptElement> elements)
        {
            g.SmoothingMode = System.Drawing.Drawing2D.SmoothingMode.AntiAlias;
            g.InterpolationMode = System.Drawing.Drawing2D.InterpolationMode.HighQualityBicubic;
            g.PixelOffsetMode = System.Drawing.Drawing2D.PixelOffsetMode.HighQuality;

            // ── THE one safe content rectangle — everything below reads
            // ONLY these values for horizontal layout. The border itself
            // (DrawOuterBorder) still sits at the hard ContentLeft/
            // ContentRight boundary; BorderInnerPaddingPx only insets what
            // gets drawn, so text/logo/QR never touch the border line.
            int contentLeftPx = ReceiptLayoutConfig.ContentLeft + ReceiptLayoutConfig.BorderInnerPaddingPx;
            float contentWidth = ReceiptLayoutConfig.ContentWidth - (ReceiptLayoutConfig.BorderInnerPaddingPx * 2);
            var blackBrush = Brushes.Black;

            float y = ReceiptLayoutConfig.TopPaddingPx + ReceiptLayoutConfig.LogoTopSpacingPx;

            foreach (var el in elements)
            {
                switch (el.Type)
                {
                    case ElementType.Text:
                        {
                            var fontStyle = el.Bold ? FontStyle.Bold : FontStyle.Regular;
                            using (var font = new Font("Arial", el.FontSize, fontStyle, GraphicsUnit.Pixel))
                            {
                                // WrapTextHard — same hard guarantee as Row values.
                                // Text elements never auto-shrink (approved
                                // typography stays as-is); this only prevents a
                                // pathological unbroken string (e.g. a long
                                // failure-message word) from crossing ContentRight.
                                var lines = WrapTextHard(g, el.Text ?? "", font, contentWidth);
                                var format = new StringFormat
                                {
                                    Alignment = el.Align == TextAlign.Center ? StringAlignment.Center
                                        : el.Align == TextAlign.Right ? StringAlignment.Far
                                        : StringAlignment.Near
                                };
                                foreach (var line in lines)
                                {
                                    var lineSize = g.MeasureString(line, font, (int)contentWidth, format);
                                    g.DrawString(line, font, blackBrush,
                                        new RectangleF(contentLeftPx, y, contentWidth, lineSize.Height + ReceiptLayoutConfig.TextLineSpacingPx),
                                        format);
                                    y += lineSize.Height + ReceiptLayoutConfig.TextLineSpacingPx;
                                }
                            }
                            break;
                        }

                    case ElementType.Row:
                        {
                            float gap = ReceiptLayoutConfig.RowColumnGapPx;
                            float leftColWidth = (contentWidth * ReceiptLayoutConfig.RowLeftWidthRatio) - (gap / 2f);
                            float rightColWidth = (contentWidth * ReceiptLayoutConfig.RowRightWidthRatio) - (gap / 2f);
                            float rightColX = contentLeftPx + contentWidth - rightColWidth; // flush to ContentRight

                            var leftStyle = FontStyle.Regular;
                            var rightStyle = el.RightBold ? FontStyle.Bold : FontStyle.Regular;

                            // Right value: try approved size on one line first;
                            // auto-shrink (never clip) if it doesn't fit.
                            using (var rightFont = FitFontToWidth(g, el.RightText, "Arial", el.RightFontSize, rightStyle, rightColWidth))
                            using (var leftFont = FitFontToWidth(g, el.LeftText, "Arial", el.LeftFontSize, leftStyle, leftColWidth))
                            {
                                // WrapTextHard (not plain WrapText) — guarantees
                                // every line fits, breaking character-by-character
                                // as a last resort for a still-unbreakable value.
                                var rightLines = WrapTextHard(g, el.RightText ?? "", rightFont, rightColWidth);
                                var leftLines = WrapTextHard(g, el.LeftText ?? "", leftFont, leftColWidth);

                                float leftLineH = g.MeasureString("Xg", leftFont).Height;
                                float rightLineH = g.MeasureString("Xg", rightFont).Height;
                                float leftBlockH = leftLines.Count * (leftLineH + ReceiptLayoutConfig.RowLineSpacingPx);
                                float rightBlockH = rightLines.Count * (rightLineH + ReceiptLayoutConfig.RowLineSpacingPx);
                                float rowHeight = Math.Max(leftBlockH, rightBlockH);

                                float ly = y;
                                foreach (var line in leftLines)
                                {
                                    g.DrawString(line, leftFont, blackBrush,
                                        new RectangleF(contentLeftPx, ly, leftColWidth, leftLineH + ReceiptLayoutConfig.RowLineSpacingPx),
                                        new StringFormat { Alignment = StringAlignment.Near });
                                    ly += leftLineH + ReceiptLayoutConfig.RowLineSpacingPx;
                                }

                                float ry = y;
                                foreach (var line in rightLines)
                                {
                                    g.DrawString(line, rightFont, blackBrush,
                                        new RectangleF(rightColX, ry, rightColWidth, rightLineH + ReceiptLayoutConfig.RowLineSpacingPx),
                                        new StringFormat { Alignment = StringAlignment.Far });
                                    ry += rightLineH + ReceiptLayoutConfig.RowLineSpacingPx;
                                }

                                y += rowHeight;
                            }
                            break;
                        }

                    case ElementType.Image:
                        {
                            if (el.ImageHeightPx == -1)
                            {
                                var logo = GetProcessedLogo();
                                if (logo != null)
                                {
                                    // Hard-capped to LogoMaxWidthPx (< ContentWidth) —
                                    // never allowed to exceed the safe content area,
                                    // regardless of the source PNG's native size.
                                    float scale = Math.Min((float)ReceiptLayoutConfig.LogoMaxWidthPx / logo.Width, 1f);
                                    float w = logo.Width * scale;
                                    float h = logo.Height * scale;
                                    float x = contentLeftPx + (contentWidth - w) / 2f;
                                    g.DrawImage(logo, x, y, w, h);
                                    y += h;
                                }
                            }
                            else if (!string.IsNullOrEmpty(el.ImageBase64))
                            {
                                try
                                {
                                    byte[] bytes = Convert.FromBase64String(StripDataUriPrefix(el.ImageBase64));
                                    using (var ms = new MemoryStream(bytes))
                                    using (var img = Image.FromStream(ms))
                                    {
                                        float maxW = contentWidth;
                                        float scale = Math.Min(el.ImageHeightPx / (float)img.Height, maxW / img.Width);
                                        float w = img.Width * scale;
                                        float h = img.Height * scale;
                                        float x = contentLeftPx + (contentWidth - w) / 2f;
                                        g.DrawImage(img, x, y, w, h);
                                        y += h + 6;
                                    }
                                }
                                catch (Exception imgEx)
                                {
                                    Program.Log("Image element failed to draw: " + imgEx.Message);
                                    y += 4;
                                }
                            }
                            break;
                        }

                    case ElementType.QrCode:
                        {
                            // Dynamic, per-ticket — generated here, never stored.
                            if (!string.IsNullOrEmpty(el.QrText))
                            {
                                try
                                {
                                    using (var qrGen = new QRCodeGenerator())
                                    using (var qrData = qrGen.CreateQrCode(el.QrText, QRCodeGenerator.ECCLevel.M))
                                    using (var qrCode = new QRCode(qrData))
                                    using (var qrBmp = qrCode.GetGraphic(20, Color.Black, Color.White, true))
                                    {
                                        // Square, capped well inside ContentWidth.
                                        int size = Math.Min(ReceiptLayoutConfig.QrDisplaySizePx, (int)contentWidth);
                                        float x = contentLeftPx + (contentWidth - size) / 2f;
                                        y += ReceiptLayoutConfig.QrTopSpacingPx;
                                        g.DrawImage(qrBmp, x, y, size, size);
                                        y += size;

                                        if (!string.IsNullOrEmpty(el.QrLabel))
                                        {
                                            y += ReceiptLayoutConfig.QrLabelSpacingPx;
                                            using (var labelFont = new Font("Arial", ReceiptLayoutConfig.QrLabelFontSize, FontStyle.Regular, GraphicsUnit.Pixel))
                                            {
                                                var lines = WrapTextHard(g, el.QrLabel, labelFont, contentWidth);
                                                foreach (var line in lines)
                                                {
                                                    var lineSize = g.MeasureString(line, labelFont, (int)contentWidth);
                                                    g.DrawString(line, labelFont, blackBrush,
                                                        new RectangleF(contentLeftPx, y, contentWidth, lineSize.Height + ReceiptLayoutConfig.TextLineSpacingPx),
                                                        new StringFormat { Alignment = StringAlignment.Center });
                                                    y += lineSize.Height + ReceiptLayoutConfig.TextLineSpacingPx;
                                                }
                                            }
                                        }
                                    }
                                }
                                catch (Exception qrEx)
                                {
                                    Program.Log("QrCode element failed to draw: " + qrEx.Message);
                                }
                            }
                            break;
                        }

                    case ElementType.Divider:
                        {
                            using (var pen = new Pen(Color.Black, 1))
                            {
                                g.DrawLine(pen, contentLeftPx, y + (ReceiptLayoutConfig.DividerSpacingPx / 2f),
                                    contentLeftPx + contentWidth, y + (ReceiptLayoutConfig.DividerSpacingPx / 2f));
                            }
                            y += ReceiptLayoutConfig.DividerSpacingPx + 4;
                            break;
                        }

                    case ElementType.Spacer:
                        y += el.HeightPx;
                        break;
                }
            }

            return (int)y + ReceiptLayoutConfig.FooterSpacingPx + ReceiptLayoutConfig.BottomPaddingPx;
        }

        private static string StripDataUriPrefix(string base64)
        {
            int comma = base64.IndexOf(',');
            return comma >= 0 ? base64.Substring(comma + 1) : base64;
        }
    }
